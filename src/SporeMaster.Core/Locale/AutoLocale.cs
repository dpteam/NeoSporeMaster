using SporeMaster.Core.Names;
using SporeMaster.Core.Properties;

namespace SporeMaster.Core.Locale;

/// <summary>
/// Generates the "auto" locale tables that SporeMaster 2 created for property files whose
/// <c>text</c> entries only had placeholder text (no table/instance id).
/// </summary>
/// <remarks>
/// Placeholder texts (e.g. the visible fallback string in a mod) are collected into a locale
/// table named <c>auto_&lt;group&gt;_&lt;instance&gt;</c>; each entry gets the next sequential
/// instance id and the property is rewritten to reference it. This mirrors
/// <c>PackagePack.generateLocale</c> from SporeMaster 2 and the auto-locale handling in
/// SporeModder FX.
/// </remarks>
public static class AutoLocale
{
    /// <summary>The group id of the <c>locale~</c> folder.</summary>
    public const uint LocaleGroup = 0x02FABF01;

    /// <summary>Builds the conventional auto-locale name for a property resource.</summary>
    public static string GetName(string groupName, string instanceName) => $"auto_{groupName}_{instanceName}";

    /// <summary>
    /// Scans <paramref name="list"/> for placeholder texts, assigns them the locale table/instance
    /// ids (mutating the list) and returns the generated table, or null when there is nothing to do.
    /// </summary>
    public static LocaleTable? Generate(PropertyList list, string localeName, NameRegistrySet names)
    {
        uint tableId = names.GetFileHash(localeName);
        LocaleTable? table = null;
        uint index = 0;

        foreach (Property property in list.Properties.Values)
        {
            if (property is not TextProperty text)
            {
                continue;
            }

            foreach (LocalizedText value in text.Values)
            {
                if (value.TableId != 0 || value.InstanceId != 0)
                {
                    continue;
                }

                table ??= new LocaleTable
                {
                    HeaderComment = "This file was autogenerated by SporeMaster 3",
                };

                index++;
                value.TableId = tableId;
                value.InstanceId = index;
                table.Add(index, value.Text);
            }
        }

        return table;
    }

    /// <summary>True when the name of <paramref name="tableId"/> looks like an auto-generated locale.</summary>
    public static bool IsAutoLocale(NameRegistrySet names, uint tableId) =>
        IsAutoLocaleName(names.GetFileName(tableId));

    /// <summary>True when a locale table name follows the auto-generated convention.</summary>
    public static bool IsAutoLocaleName(string name) =>
        name.StartsWith("auto_", StringComparison.OrdinalIgnoreCase) ||
        name.EndsWith("_auto", StringComparison.OrdinalIgnoreCase);

    /// <summary>
    /// True when a locale table's content marks it as auto-generated (by SporeMaster or
    /// SporeModder). This works even when the table name is unknown, which makes it a robust
    /// signal for cleaning up generated locales during unpacking.
    /// </summary>
    public static bool IsAutoLocaleContent(string content)
    {
        // Only inspect the leading comment block.
        foreach (string rawLine in content.Split('\n'))
        {
            string line = rawLine.Trim();
            if (line.Length == 0)
            {
                continue;
            }

            if (!line.StartsWith('#'))
            {
                break; // first real entry -> no more comments
            }

            string lower = line.ToLowerInvariant();
            if (lower.Contains("autogenerated by sporemodder") ||
                lower.Contains("autogenerated by sporemaster") ||
                lower.Contains("generated from") && lower.Contains("by sporemaster"))
            {
                return true;
            }
        }

        return false;
    }
}
