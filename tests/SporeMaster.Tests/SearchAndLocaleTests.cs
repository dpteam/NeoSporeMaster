using SporeMaster.Core.Locale;
using SporeMaster.Core.Search;

namespace SporeMaster.Tests;

public static class SearchAndLocaleTests
{
    [SporeTest("search index finds matches with line numbers")]
    public static void SearchFinds()
    {
        var index = new SearchIndex();
        index.AddText("a.txt", "alpha\nBETA gamma\nbeta delta\n");

        IReadOnlyList<SearchMatch> hits = index.Search("beta");
        Assert.Equal(2, hits.Count);
        Assert.Equal(2, hits[0].LineNumber);
        Assert.Equal(3, hits[1].LineNumber);
        Assert.Contains(hits[1].Line, "beta delta");
    }

    [SporeTest("search index skips binary files")]
    public static void SearchSkipsBinary()
    {
        string dir = TestData.CreateTempDirectory();
        try
        {
            File.WriteAllText(Path.Combine(dir, "text.txt"), "hello world\n");
            File.WriteAllBytes(Path.Combine(dir, "blob.bin"), new byte[] { 0, 1, 2, 0, 3, 4 });

            SearchIndex index = SearchIndex.BuildFromDirectory(dir);
            Assert.Equal(1, index.FileCount);
            Assert.Equal(1, index.Skipped.Count);

            Assert.Equal(1, index.Search("hello").Count);
        }
        finally
        {
            TestData.DeleteDirectory(dir);
        }
    }

    [SporeTest("search index respects the extension filter")]
    public static void SearchExtensionFilter()
    {
        string dir = TestData.CreateTempDirectory();
        try
        {
            File.WriteAllText(Path.Combine(dir, "a.prop.xml"), "needle\n");
            File.WriteAllText(Path.Combine(dir, "b.txt"), "needle\n");

            SearchIndex index = SearchIndex.BuildFromDirectory(dir, new[] { ".prop.xml" });
            Assert.Equal(1, index.FileCount);
        }
        finally
        {
            TestData.DeleteDirectory(dir);
        }
    }

    [SporeTest("auto-locale content is recognised")]
    public static void AutoLocaleContent()
    {
        Assert.True(AutoLocale.IsAutoLocaleContent("# This file was autogenerated by SporeMaster 3\n0x1 x\n"));
        Assert.True(AutoLocale.IsAutoLocaleContent("# This file generated from g/i.prop.xml by SporeMaster.\n0x1 x\n"));
        Assert.True(AutoLocale.IsAutoLocaleContent("# This file was autogenerated by SporeModder\n0x1 x\n"));
        Assert.False(AutoLocale.IsAutoLocaleContent("# A hand-written table\n0x1 x\n"));
        Assert.False(AutoLocale.IsAutoLocaleContent("0x1 x\n# comment after data\n"));
    }
}
